"""Session persistence: JSON context + JSONL history."""

from __future__ import annotations

import asyncio
import shutil
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

from amrita_core.types import MemoryModel
from amrita_core.types.message import Message
from amrita_sense.logging import logger
from pydantic import BaseModel, Field

from app.core.config import PATHS
from app.core.storage import (
    append_jsonl,
    read_json,
    read_jsonl,
    write_json,
)
from app.runtime import session_memory
from app.runtime.billing import TurnUsage, UsageTotals

Role = Literal["user", "assistant", "system", "tool"]


class SessionMeta(BaseModel):
    id: str
    title: str = "新会话"
    created_at: float = Field(default_factory=time.time)
    updated_at: float = Field(default_factory=time.time)
    preset: str | None = None
    agent: str | None = None
    # Use the global workspace when this session has no stored workspace.
    workspace: str | None = None
    message_count: int = 0
    usage: UsageTotals = Field(default_factory=UsageTotals)
    # Archived sessions are hidden from the sidebar but still on disk.
    archived: bool = False
    archived_at: float | None = None
    # Session this one was branched from, and the entry it started at.
    parent_id: str | None = None
    branch_from: str | None = None
    branch_index: int | None = None


class HistoryEntry(BaseModel):
    """One visible chat bubble. Tool traffic stays in the JSON context only."""

    id: str = Field(default_factory=lambda: uuid.uuid4().hex)
    role: Role
    content: str
    created_at: float = Field(default_factory=time.time)
    reasoning: str | None = None
    events: list[dict[str, Any]] = Field(default_factory=list)
    error: str | None = None
    usage: TurnUsage | None = None
    steps: int = 0
    tool_calls: int = 0
    workflow: str | None = None
    agent: str | None = None
    # Images pasted into the composer / long pastes stored as files.
    attachments: list[dict[str, Any]] = Field(default_factory=list)


def _session_dir(session_id: str) -> Path:
    # Session ids are generated by us; reject separators defensively anyway.
    if "/" in session_id or "\\" in session_id or session_id in {"", ".", ".."}:
        raise ValueError("invalid session id")
    return PATHS.sessions / session_id


def context_path(session_id: str) -> Path:
    return _session_dir(session_id) / "context.json"


def history_path(session_id: str) -> Path:
    return _session_dir(session_id) / "history.jsonl"


def meta_path(session_id: str) -> Path:
    return _session_dir(session_id) / "meta.json"


def usage_path(session_id: str) -> Path:
    return _session_dir(session_id) / "usage.jsonl"


async def load_usage(session_id: str) -> list[TurnUsage]:
    raw = await read_jsonl(usage_path(session_id))
    out: list[TurnUsage] = []
    for item in raw:
        try:
            out.append(TurnUsage.model_validate(item))
        except ValueError:
            logger.warning(f"Skipping unreadable usage entry in session {session_id}")
    return out


async def append_usage(session_id: str, usage: TurnUsage) -> None:
    await append_jsonl(usage_path(session_id), usage.model_dump())


async def record_turn_usage(
    session_id: str, usage: TurnUsage
) -> tuple[UsageTotals, SessionMeta | None]:
    """Persist one turn and fold its numbers into the session totals."""
    await append_usage(session_id, usage)
    meta = await get_meta(session_id)
    if meta is None:
        return UsageTotals(), None
    totals = meta.usage.model_copy(deep=True)
    totals.add(usage)
    meta.usage = totals
    await save_meta(meta)
    return totals, meta


async def list_sessions(include_archived: bool = False) -> list[SessionMeta]:
    PATHS.ensure()
    out: list[SessionMeta] = []
    for child in PATHS.sessions.iterdir():
        if not child.is_dir():
            continue
        raw = await read_json(child / "meta.json")
        if not raw:
            continue
        try:
            meta = SessionMeta.model_validate(raw)
        except ValueError:
            # A half-written or hand-edited meta file must not hide the rest.
            logger.warning(f"Skipping unreadable session meta: {child}")
            continue
        if meta.archived and not include_archived:
            continue
        out.append(meta)
    out.sort(key=lambda m: m.updated_at, reverse=True)
    return out


async def create_session(
    title: str = "新会话",
    preset: str | None = None,
    *,
    workspace: str | None = None,
    agent: str | None = None,
) -> SessionMeta:
    """Create a session, snapshotting the defaults it should keep.

    Workspace and agent are copied from the current defaults rather than looked
    up on every turn: switching workspace in another session must not move this
    conversation's files under it.
    """
    PATHS.ensure()
    meta = SessionMeta(
        id=uuid.uuid4().hex,
        title=title,
        preset=preset,
        workspace=workspace,
        agent=agent,
    )
    _session_dir(meta.id).mkdir(parents=True, exist_ok=True)
    await write_json(meta_path(meta.id), meta.model_dump())
    await write_json(context_path(meta.id), MemoryModel().model_dump(mode="json"))
    history_path(meta.id).touch()
    usage_path(meta.id).touch()
    return meta


async def set_session_config(
    session_id: str,
    *,
    workspace: str | None = None,
    agent: str | None = None,
) -> SessionMeta | None:
    """Point one session at a workspace and/or an agent.

    ``None`` means "leave as is", so a client can set either field alone. The
    change applies to the next turn; a running turn keeps the copy it started
    with.
    """
    meta = await get_meta(session_id)
    if meta is None:
        return None
    if workspace is not None:
        meta.workspace = workspace
    if agent is not None:
        meta.agent = agent
    await save_meta(meta)
    return meta


async def get_meta(session_id: str) -> SessionMeta | None:
    raw = await read_json(meta_path(session_id))
    return SessionMeta.model_validate(raw) if raw else None


async def save_meta(meta: SessionMeta) -> None:
    meta.updated_at = time.time()
    await write_json(meta_path(meta.id), meta.model_dump())


async def delete_session(session_id: str) -> bool:
    directory = _session_dir(session_id)
    if not directory.exists():
        return False
    await asyncio.to_thread(shutil.rmtree, directory, True)
    return True


async def archive_session(session_id: str, archived: bool = True) -> SessionMeta | None:
    """Hide a session from the sidebar without touching its files.

    Deleting stays possible, but only from the archive: the destructive action
    should require looking at what is about to be lost.
    """
    meta = await get_meta(session_id)
    if meta is None:
        return None
    meta.archived = archived
    meta.archived_at = time.time() if archived else None
    await save_meta(meta)
    return meta


async def branch_session(
    session_id: str,
    *,
    index: int | None = None,
    title: str | None = None,
    entry_id: str | None = None,
) -> SessionMeta | None:
    """Fork a session into a new one.

    ``index`` is a position in the visible transcript: everything before it is
    copied, everything after is left behind. ``None`` clones the whole
    conversation. ``entry_id`` names the bubble to fork at, and keeps it: the
    new session ends with that message.

    Forking at a *user* message is allowed on purpose. Consecutive user turns
    are valid (OpenAI accepts them), so "keep everything up to this prompt and
    let me say it differently" is a normal edit, not something to block until
    the model has replied.

    The copy's memory is rebuilt from the copied bubbles rather than sliced out
    of the original ``MemoryModel``, because the memory also holds tool traffic
    that the UI never showed — a branch should continue from exactly what the
    user can see.
    """
    source = await get_meta(session_id)
    if source is None:
        return None

    entries = await load_history(session_id)
    if entry_id is not None:
        position = next((i for i, entry in enumerate(entries) if entry.id == entry_id), None)
        if position is None:
            raise ValueError("history entry not found")
        index = position + 1
    keep = entries if index is None else entries[: max(0, index)]

    memory = await load_context(session_id)
    if index is not None:
        rebuilt: list[Any] = []
        for entry in keep:
            if entry.role not in {"user", "assistant"} or not entry.content.strip():
                continue
            # Exclude UI-only commands when rebuilding a branch's model context.
            if entry.workflow == "command":
                continue
            role: Literal["user", "assistant"] = "user" if entry.role == "user" else "assistant"
            rebuilt.append(Message(role=role, content=entry.content))
        memory.messages = rebuilt

    label = title or f"{source.title} · 分支"
    meta = SessionMeta(
        id=uuid.uuid4().hex,
        title=label,
        preset=source.preset,
        agent=source.agent,
        # A branch continues the same work, in the same directory.
        workspace=source.workspace,
        parent_id=source.id,
        branch_from=source.id,
        branch_index=index if index is not None else len(entries),
    )
    _session_dir(meta.id).mkdir(parents=True, exist_ok=True)
    await write_json(meta_path(meta.id), meta.model_dump())
    await save_context(meta.id, memory)
    for entry in keep:
        await append_history(meta.id, entry)
    if not keep:
        history_path(meta.id).touch()
    usage_path(meta.id).touch()
    meta.message_count = sum(1 for entry in keep if entry.role == "user")
    await save_meta(meta)
    return meta


async def branches_of(session_id: str) -> list[SessionMeta]:
    """Sessions that were forked from ``session_id``, oldest first."""
    children = [
        meta for meta in await list_sessions(include_archived=True) if meta.parent_id == session_id
    ]
    children.sort(key=lambda m: m.created_at)
    return children


async def clear_session(session_id: str) -> bool:
    meta = await get_meta(session_id)
    if meta is None:
        return False
    await save_context(session_id, MemoryModel())
    # The plan belongs to the history being cleared, so the scratch directory goes too.
    await asyncio.to_thread(session_memory.clear, session_id)
    for path in (history_path(session_id), usage_path(session_id)):
        if path.exists():
            path.unlink()
        path.touch()
    meta.message_count = 0
    meta.usage = UsageTotals()
    await save_meta(meta)
    return True


async def load_context(session_id: str) -> MemoryModel:
    raw = await read_json(context_path(session_id))
    if not raw:
        return MemoryModel()
    return MemoryModel.model_validate(raw)


async def save_context(session_id: str, memory: MemoryModel) -> None:
    await write_json(context_path(session_id), memory.model_dump(mode="json"))


async def load_history(session_id: str) -> list[HistoryEntry]:
    raw = await read_jsonl(history_path(session_id))
    out: list[HistoryEntry] = []
    for item in raw:
        try:
            out.append(HistoryEntry.model_validate(item))
        except ValueError:
            logger.warning(f"Skipping unreadable history entry in session {session_id}")
            continue
    return out


async def append_history(session_id: str, entry: HistoryEntry) -> None:
    await append_jsonl(history_path(session_id), entry.model_dump())


async def bump_session(session_id: str, *, title: str | None = None) -> SessionMeta | None:
    meta = await get_meta(session_id)
    if meta is None:
        return None
    if title:
        meta.title = title
    meta.message_count += 1
    await save_meta(meta)
    return meta


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()
